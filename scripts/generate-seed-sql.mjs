// Turns src/data/seed-products.js into a migration that defines seed_catalog().
//
// The catalog is per-household, so it cannot be a plain INSERT in a migration —
// it ships as a function the admin calls once, right after creating the house.
//
//   npm run seed:sql

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { SEED_PRODUCTS } from '../src/data/seed-products.js'

const here = dirname(fileURLToPath(import.meta.url))
const out = join(here, '..', 'supabase', 'migrations', '0004_seed_catalog.sql')

const q = (s) => `'${String(s).replace(/'/g, "''")}'`
const arr = (a) =>
  a.length ? `array[${a.map(q).join(',')}]::text[]` : `'{}'::text[]`

const rows = SEED_PRODUCTS.map(
  ([name, dept, unit, qty, icon, aliases]) =>
    `    (${q(name)}, ${q(dept)}, ${q(unit)}, ${qty}, ${q(icon)}, ${arr(aliases)})`,
).join(',\n')

const sql = `-- השלמות — seed catalog (generated by scripts/generate-seed-sql.mjs, do not edit)
--
-- ${SEED_PRODUCTS.length} products across 15 departments, each with an icon, a
-- department and the unit a person actually buys it in. This is what lets Mom
-- type two letters and pick instead of describing a product from scratch.

create or replace function public.seed_catalog()
returns int
language plpgsql set search_path = public
as $$
declare
  v_household uuid := public.current_household_id();
  v_count     int;
begin
  if v_household is null then
    raise exception 'not a member of any household';
  end if;

  insert into products (household_id, name, department_key, default_unit,
                        default_qty, icon, aliases, is_seed)
  select v_household, s.name, s.dept, s.unit, s.qty, s.icon, s.aliases, true
  from (values
${rows}
  ) as s(name, dept, unit, qty, icon, aliases)
  -- Safe to re-run: never duplicates a name already in the house.
  where not exists (
    select 1 from products p
    where p.household_id = v_household and p.name = s.name
  );

  get diagnostics v_count = row_count;
  return v_count;
end $$;

grant execute on function public.seed_catalog() to authenticated;
`

writeFileSync(out, sql, 'utf8')
console.log(`wrote ${out} — ${SEED_PRODUCTS.length} products`)
